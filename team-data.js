// ── Consulta ──
// Casa o nome da planilha com o usuário cadastrado (mesma normalização da
// importação de clientes: ignora acento, caixa e apóstrofo).
function tdNorm(s){return String(s===undefined||s===null?'':s).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,'').replace(/[^a-z0-9 ]/g,'').replace(/\s+/g,' ').trim();}
var _tdIndex=null;
function tdIndex(){
  if(_tdIndex)return _tdIndex;
  _tdIndex={};
  TEAM_ANALYSTS.forEach(function(a){_tdIndex[tdNorm(a.name)]=a;});
  return _tdIndex;
}
// Aceita o objeto de usuário do dashboard ou o nome cru.
function tdForUser(u){
  var name=(u&&u.name)||u||'';
  var idx=tdIndex();
  var hit=idx[tdNorm(name)];
  if(hit)return hit;
  // fallback: primeiro + último nome (Caroline Curcio vs Caroline C. Curcio)
  var p=tdNorm(name).split(' ');
  if(p.length<2)return null;
  var first=p[0],last=p[p.length-1];
  var keys=Object.keys(idx).filter(function(k){var q=k.split(' ');return q[0]===first&&q[q.length-1]===last;});
  return keys.length===1?idx[keys[0]]:null;
}
function tdMonthKey(d){
  d=d||new Date();
  var m=d.getMonth()+1;
  return d.getFullYear()+'-'+(m<10?'0':'')+m;
}
// Meses com dado, do mais antigo ao mês corrente (não mostra mês futuro).
function tdMonthsUpToNow(count){
  var now=tdMonthKey();
  var list=TEAM_MONTHS.filter(function(m){return m<=now;});
  return count?list.slice(-count):list;
}
// Soma um campo entre os analistas informados (ou todos) num intervalo de meses.
function tdSum(field,months,analysts){
  var list=analysts||TEAM_ANALYSTS;
  var total=0,found=false;
  list.forEach(function(a){
    if(!a)return;
    months.forEach(function(m){
      var v=a[field]&&a[field][m];
      if(v!==undefined&&v!==null){total+=v;found=true;}
    });
  });
  return found?total:null;
}
// Atingimento no formato da planilha: soma(realizado)/soma(meta).
function tdAttainment(realField,metaField,months,analysts){
  var real=tdSum(realField,months,analysts);
  var meta=tdSum(metaField,months,analysts);
  if(meta===null||!meta)return null;
  return{real:real||0,meta:meta,pct:Math.round((real||0)/meta*1000)/10};
}
